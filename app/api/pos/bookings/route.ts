import { db, isUniqueViolation } from "@/lib/db/db";
import { bookings, payments, courts } from "@/lib/db/schema";
import { eq, and } from "drizzle-orm";
import { NextRequest, NextResponse } from "next/server";
import { requireAdmin } from "@/lib/server-auth";
import { calculateBookingAmountForCourt } from "@/lib/pricing";
import { sendBookingSms } from "@/lib/sms";

// POST /api/pos/bookings - A walk-in court booking rung up at the counter.
// Separate from the public POST /api/bookings rather than overloading it:
// that route's contract (defaults to unpaid/pay-at-venue) is for online/
// guest bookings and stays exactly as it is. Here, money was just taken at
// the counter, so the booking AND its payment are both marked
// confirmed/completed immediately.
//
// `id` is generated by the till itself for the same offline-queue
// idempotency reason as /api/pos/sales - a resynced retry of an already-
// landed booking is a no-op, not a double booking.
export async function POST(request: NextRequest) {
  const auth = await requireAdmin(request);
  if (auth.response) return auth.response;

  try {
    const body = await request.json();
    const {
      id,
      courtId,
      bookingDate,
      startTime,
      endTime,
      numPlayers,
      paymentMethod,
      customerName,
      customerPhone,
    } = body as {
      id: string;
      courtId: string;
      bookingDate: string;
      startTime: string;
      endTime: string;
      numPlayers: number;
      paymentMethod: "cash" | "card";
      customerName: string;
      customerPhone: string;
    };

    if (!id || !courtId || !bookingDate || !startTime || !endTime || !numPlayers || !paymentMethod || !customerName) {
      return NextResponse.json({ error: "Missing required fields" }, { status: 400 });
    }

    // Already synced by an earlier attempt - return it as-is.
    const existing = await db.select().from(bookings).where(eq(bookings.id, id)).limit(1);
    if (existing.length) {
      return NextResponse.json({ booking: existing[0] }, { status: 200 });
    }

    const amountLkr = await calculateBookingAmountForCourt(courtId, startTime, endTime);

    const slotTaken = await db
      .select()
      .from(bookings)
      .where(
        and(
          eq(bookings.courtId, courtId),
          eq(bookings.bookingDate, bookingDate),
          eq(bookings.startTime, startTime),
          eq(bookings.status, "confirmed")
        )
      )
      .limit(1);
    if (slotTaken.length > 0) {
      return NextResponse.json({ error: "Slot already booked" }, { status: 409 });
    }

    const newBooking = await db
      .insert(bookings)
      .values({
        id,
        userId: null,
        courtId,
        bookingDate,
        startTime,
        endTime,
        numPlayers,
        guestName: customerName,
        guestPhone: customerPhone || null,
        guestEmail: null,
        amountLkr: amountLkr.toString(),
        status: "confirmed",
        paymentStatus: "paid",
        notes: `Walk-in - rung up at the counter by ${auth.user.fullName} (${paymentMethod})`,
        checkedInAt: new Date(), // walking in means they're already here
      })
      .returning();

    await db.insert(payments).values({
      bookingId: id,
      userId: null,
      amountLkr: amountLkr.toString(),
      gateway: "manual",
      status: "completed",
    });

    if (customerPhone) {
      const court = await db.select({ name: courts.name }).from(courts).where(eq(courts.id, courtId)).limit(1);
      await sendBookingSms(customerPhone, {
        courtName: court[0]?.name ?? "the court",
        bookingDate,
        startTime,
        bookingRef: id,
      });
    }

    return NextResponse.json({ booking: newBooking[0] }, { status: 201 });
  } catch (error) {
    if (isUniqueViolation(error)) {
      return NextResponse.json({ error: "Slot already booked" }, { status: 409 });
    }
    console.error("Create POS booking error:", error);
    return NextResponse.json({ error: "Failed to create booking" }, { status: 500 });
  }
}
